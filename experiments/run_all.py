"""Run every experiment and write results/results.md (about 6 minutes)."""

from __future__ import annotations

import os
import platform
import time

import numpy as np

from experiments import e1_derivatives, e2_convergence, e3_sampling, e4_mpc
from experiments.common import RESULTS


def main():
    parts = ["# Results", "",
             f"Generated by `python3 -m experiments.run_all` (Python {platform.python_version()}, "
             f"NumPy {np.__version__}). Everything is a simulation; timings are single-threaded "
             "Python wall-clock on one machine and only meaningful relative to each other.", ""]
    for mod in (e1_derivatives, e2_convergence, e3_sampling, e4_mpc):
        t0 = time.perf_counter()
        parts.append(mod.run())
        print(f"{mod.__name__}: {time.perf_counter() - t0:.1f} s", flush=True)
    with open(os.path.join(RESULTS, "results.md"), "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    np.seterr(all="ignore")
    main()
